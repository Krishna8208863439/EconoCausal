import React, { useState } from 'react'
import SectionCard from '../components/SectionCard.jsx'
import PlannedFeature from '../components/PlannedFeature.jsx'
import './Page.css'

const CONFOUNDERS = ['age_group','past_purchases','avg_order_value','website_visits','customer_segment']
const EXCLUDED    = [
  { name: 'customer_id',     reason: 'Identifier — no causal meaning. Would create spurious one-to-one mapping.' },
  { name: 'discount_amount', reason: 'Set after treatment assignment — treatment attribute, not a confounder.' },
  { name: 'revenue',         reason: 'Post-treatment — conditioning opens collider bias paths.' },
  { name: 'campaign_date',   reason: 'Administrative timestamp — no causal relationship with outcome.' },
]

export default function CausalPage() {
  const [dagError, setDagError] = useState(false)

  return (
    <div className="page">
      <div className="page-header">
        <h1 className="page-title">Causal Analysis</h1>

      </div>

      <div className="notice-banner notice-banner--info">
        <span aria-hidden="true">ℹ️</span>
        <span>
          A Directed Acyclic Graph (DAG) represents <em>assumptions</em> about the
          data-generating process. It does not prove causation. Causal identification
          depends on the assumptions listed below being valid.
        </span>
      </div>

      <SectionCard title="Causal Question">
        <blockquote className="causal-question">
          Does offering a promotional discount <strong>cause</strong> an increase in
          purchase probability?
        </blockquote>
        <p className="prose">
          Formally, we want to estimate the <strong>Average Treatment Effect (ATE)</strong>:
        </p>
        <div className="math-block" aria-label="ATE formula">
          τ = E[Y(1) − Y(0)]
        </div>
        <p className="prose">
          where <em>Y(1)</em> is the potential outcome with a discount and <em>Y(0)</em> is
          the potential outcome without one. Because we cannot observe both for the same
          customer, we estimate the ATE using causal assumptions and Double Machine Learning.
        </p>
      </SectionCard>

      <SectionCard title="Causal DAG" badge="DoWhy 0.8">
        <p className="prose" style={{marginBottom: '16px'}}>
          Generated by <code>src/causal/build_dag.py</code> using DoWhy and networkx.
          Each confounder has edges to both <strong>treatment</strong> (discount offering
          decision) and <strong>outcome</strong> (purchase), representing selection bias.
        </p>

        {!dagError ? (
          <div className="dag-container">
            <img
              src="/causal_dag.png"
              alt="Causal DAG: confounders influence both discount_offered (treatment) and purchased (outcome)"
              className="dag-image"
              onError={() => setDagError(true)}
            />
          </div>
        ) : (
          <div className="dag-placeholder" role="img" aria-label="Causal DAG diagram">
            <div className="dag-ascii">
              <div className="dag-row confounders-row">
                {CONFOUNDERS.map(c => (
                  <span key={c} className="dag-node dag-node--confounder">{c}</span>
                ))}
              </div>
              <div className="dag-arrows">↙ ↙ ↓ ↘ ↘ &nbsp;&nbsp;&nbsp; ↙ ↙ ↓ ↘ ↘</div>
              <div className="dag-row middle-row">
                <span className="dag-node dag-node--treatment">discount_offered</span>
                <span className="dag-edge">───────────→</span>
                <span className="dag-node dag-node--outcome">purchased</span>
              </div>
            </div>
            <p className="dag-placeholder__hint">
              DAG image not found at <code>/causal_dag.png</code>. Run <code>python src/causal/build_dag.py</code>
              and copy <code>reports/figures/causal_dag.png</code> to <code>frontend/public/causal_dag.png</code>.
            </p>
          </div>
        )}

        <div className="dag-legend">
          <span className="dag-legend__item"><span className="dot dot--orange"/>Pre-treatment confounder</span>
          <span className="dag-legend__item"><span className="dot dot--blue"/>Treatment (discount_offered)</span>
          <span className="dag-legend__item"><span className="dot dot--green"/>Outcome (purchased)</span>
        </div>
      </SectionCard>

      <SectionCard title="Adjustment Set">
        <h3 className="sub-heading">Included confounders</h3>
        <div className="tag-list">
          {CONFOUNDERS.map(c => (
            <span key={c} className="badge badge-orange">{c}</span>
          ))}
        </div>

        <h3 className="sub-heading" style={{marginTop: '16px'}}>Excluded variables</h3>
        <table className="col-role-table" aria-label="Excluded variables">
          <thead>
            <tr><th>Variable</th><th>Reason for exclusion</th></tr>
          </thead>
          <tbody>
            {EXCLUDED.map(e => (
              <tr key={e.name}>
                <td><code>{e.name}</code></td>
                <td>{e.reason}</td>
              </tr>
            ))}
          </tbody>
        </table>
      </SectionCard>

      <SectionCard title="Identification Assumptions">
        {[
          { name: 'Consistency (SUTVA)', body: 'The potential outcome Y(t) is well-defined. Each customer\'s outcome is not affected by another customer\'s treatment (no interference). There is one version of the discount intervention.' },
          { name: 'Positivity (Overlap)', body: 'Every customer type has a non-zero probability of receiving both treatment and control: 0 < P(T=1|X) < 1 for all observed covariate patterns X.' },
          { name: 'Conditional Exchangeability', body: 'Treatment assignment is independent of potential outcomes conditional on the five observed confounders. This is the key untestable assumption — unmeasured confounding would bias the estimate.' },
        ].map(a => (
          <div key={a.name} className="assumption-block">
            <strong>{a.name}</strong>
            <p className="prose">{a.body}</p>
          </div>
        ))}
      </SectionCard>

      <SectionCard title="Causal Concepts Glossary">
        <dl className="glossary">
          {[
            { term: 'Confounder', def: 'A variable that influences both the treatment assignment and the outcome. Must be adjusted for to identify the causal effect.' },
            { term: 'Mediator',   def: 'A variable on the causal path from treatment to outcome. Do not condition on mediators when estimating the total effect.' },
            { term: 'Collider',   def: 'A variable caused by two variables on separate causal paths. Conditioning on a collider opens a spurious association.' },
            { term: 'DAG',        def: 'Directed Acyclic Graph. A visual and formal representation of assumed causal relationships. Edges represent direct causal effects; the absence of an edge represents an assumption of no direct effect.' },
            { term: 'ATE',        def: 'Average Treatment Effect. The expected change in outcome if everyone in the population were treated versus untreated.' },
            { term: 'CATE',       def: 'Conditional Average Treatment Effect. ATE conditional on individual covariates — i.e., personalised treatment effects estimated in Week 2.' },
          ].map(g => (
            <div key={g.term} className="glossary__item">
              <dt>{g.term}</dt>
              <dd>{g.def}</dd>
            </div>
          ))}
        </dl>
      </SectionCard>

      <SectionCard title="Week 2 — Planned Estimation">
        <PlannedFeature
          week={2}
          feature="Double Machine Learning (DML) Estimator"
          description="EconML LinearDML or CausalForestDML will be used to estimate the ATE and CATE from the identified adjustment set. Propensity overlap and refutation tests will be run. Results will appear here once Week 2 is implemented."
        />
        <PlannedFeature
          week={2}
          feature="Propensity Score Overlap Plot"
          description="Distribution of estimated P(T=1|X) for treated vs. control groups, with flagging of extreme values outside the common support region."
        />
      </SectionCard>
    </div>
  )
}
